import os
import json
from typing import List, Dict, Any
from schemas import ClinicalExplanation
from train import predict_diabetes_proba, flag_abnormal_features, FEATURE_NAMES

CLINICAL_SYSTEM_PROMPT = """You are a senior clinical communication assistant embedded in the AI Health Copilot Pro decision support system.
CRITICAL SAFETY & GOVERNANCE CONSTRAINTS:
1. You are a clinical communication assistant, NOT a diagnosing physician.
2. Reason ONLY and STRICTLY from the provided deterministic abnormal flags and model probability.
3. NEVER invent or hallucinate factors, lab values, or medical history not present in the flags.
4. Output professional, concise, evidence-based physician-grade language.
5. Always include a strong, unambiguous disclaimer.
"""

DEFAULT_DISCLAIMER = (
    "CLINICAL DECISION SUPPORT NOTICE: This automated risk assessment is generated by an ML model paired with "
    "an AI clinical communication assistant. It is NOT a definitive diagnosis. All findings must be clinically "
    "correlated with venous laboratory tests (fasting plasma glucose, HbA1c) and reviewed by a licensed physician."
)

def explain_diagnosis(probability: float, flags: List[str]) -> ClinicalExplanation:
    """
    Structured clinical reasoning layer:
    Feeds ONLY the model probability + deterministic abnormal flags into the LLM.
    Uses Google GenAI / OpenAI structured response formatting.
    """
    risk_level = "high" if probability >= 0.70 else "moderate" if probability >= 0.40 else "low"

    # Fallback rule-based generator if API key is not present in local test environment
    api_key = os.getenv("GOOGLE_API_KEY") or os.getenv("GEMINI_API_KEY")
    if not api_key:
        key_factors = []
        if flags:
            for flag in flags:
                key_factors.append(f"Biomarker anomaly detected: {flag}")
        else:
            key_factors.append("Routine biomarkers (Glucose, Diastolic BP, BMI) fall within normal physiological reference ranges.")

        if risk_level == "high":
            recommendation = (
                "Expedite diagnostic fasting plasma glucose and laboratory venous HbA1c within 7–14 days. "
                "Assess for metabolic syndrome comorbidities and consider clinical referral to diabetes care team."
            )
        elif risk_level == "moderate":
            recommendation = (
                "Schedule repeat fasting metabolic panel within 90 days. Initiate lifestyle counseling on low glycemic nutrition "
                "and at least 150 minutes of moderate aerobic activity weekly."
            )
        else:
            recommendation = "Continue routine annual preventive wellness examinations and standard healthy lifestyle maintenance."

        return ClinicalExplanation(
            risk_level=risk_level,
            key_factors=key_factors,
            recommendation=recommendation,
            disclaimer=DEFAULT_DISCLAIMER
        )

    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=api_key)
        prompt_content = f"""Model Probability: {probability:.3f} ({probability*100:.1f}%)
Deterministic Abnormal Feature Flags:
{json.dumps(flags, indent=2)}

Provide a structured clinical communication report."""

        response = client.models.generate_content(
            model="gemini-2.0-flash",
            contents=prompt_content,
            config=types.GenerateContentConfig(
                system_instruction=CLINICAL_SYSTEM_PROMPT,
                response_mime_type="application/json",
                response_schema=ClinicalExplanation
            )
        )
        return ClinicalExplanation.model_validate_json(response.text)
    except Exception as exc:
        print(f"[AGENT] Falling back to deterministic clinical heuristics: {exc}")
        # Rule-based fallback
        key_factors = [f"Deterministic flag: {flag}" for flag in flags] if flags else ["All measured biomarkers within normal ranges."]
        return ClinicalExplanation(
            risk_level=risk_level,
            key_factors=key_factors,
            recommendation="Confirm with diagnostic venous HbA1c panel and licensed physician review.",
            disclaimer=DEFAULT_DISCLAIMER
        )

def run_health_copilot(patient_data: List[float]) -> Dict[str, Any]:
    """
    Main callable orchestration function:
    1. ML Model predicts diabetes probability
    2. Deterministic flagging identifies out-of-range features
    3. Structured LLM reasoning explains the clinical findings
    """
    probability = predict_diabetes_proba(patient_data)
    flags = flag_abnormal_features(patient_data, FEATURE_NAMES)
    explanation = explain_diagnosis(probability, flags)
    return {
        "probability": probability,
        "flags": flags,
        "explanation": explanation.model_dump()
    }
